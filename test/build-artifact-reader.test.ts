import { createHash } from "node:crypto";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { readBuildArtifact } from "../src/build-artifact-reader.js";
import type { BuildEvidenceManifest, BuildEvidenceRequest } from "../src/build-evidence-contract.js";
import { admitBuildEvidence, type AdmittedBuildEvidence } from "../src/build-evidence.js";
import type { SecretPolicy } from "../src/secret-screening.js";
import { createBuildFixture, fixtureRequest, type BuildFixture } from "./build-evidence-fixture.js";

const sha256 = (bytes: Uint8Array | string) => createHash("sha256").update(bytes).digest("hex");
let home: string;
let inplace: BuildFixture;
let serial = 0;

beforeAll(async () => {
  home = mkdtempSync(join(tmpdir(), "leveret-build-reader-"));
  inplace = await createBuildFixture(join(home, "in-place"), "in-place");
}, 180_000);
afterAll(() => rmSync(home, { recursive: true, force: true }));

function policy(refresh: () => Promise<readonly string[]> = async () => []): SecretPolicy {
  return {
    id: "artifact-reader-test", available: false, knownValues: new Set(), refreshKnownValues: refresh,
    additionalRules: [], nonSecretValues: new Set(),
  };
}

async function admitted(request: BuildEvidenceRequest, secretPolicy: SecretPolicy): Promise<AdmittedBuildEvidence> {
  const result = await admitBuildEvidence(request, secretPolicy);
  if (result.outcome !== "admitted") throw new Error(`expected admitted export, got ${result.outcome}`);
  return result;
}

function republishedEncoding(encoding: string): BuildEvidenceRequest {
  const dir = join(home, `encoding-${++serial}`);
  const payloadRoot = join(dir, "payload");
  const manifestPath = join(dir, "manifest.json");
  mkdirSync(dir, { recursive: true });
  cpSync(inplace.pins.head.payloadRoot, payloadRoot, { recursive: true });
  const manifest = structuredClone(inplace.manifests.head) as BuildEvidenceManifest;
  const artifact = manifest.artifacts.find((item) => item.id === "pricing-output");
  if (!artifact || artifact.availability !== "available" || artifact.kind !== "file") throw new Error("fixture output is missing");
  artifact.encoding = encoding;
  const bytes = `${JSON.stringify(manifest)}\n`;
  writeFileSync(manifestPath, bytes);
  const request = fixtureRequest(inplace, "head", join(dir, "admission"));
  return { ...request, pin: { ...request.pin!, manifestPath, payloadRoot, manifestSha256: sha256(bytes) } };
}

function republishedOutput(bytes: Buffer): BuildEvidenceRequest {
  const dir = join(home, `bytes-${++serial}`);
  const payloadRoot = join(dir, "payload");
  const manifestPath = join(dir, "manifest.json");
  mkdirSync(dir, { recursive: true });
  cpSync(inplace.pins.head.payloadRoot, payloadRoot, { recursive: true });
  const manifest = structuredClone(inplace.manifests.head) as BuildEvidenceManifest;
  const artifact = manifest.artifacts.find((item) => item.id === "pricing-output");
  if (!artifact || artifact.availability !== "available" || artifact.kind !== "file" ||
    artifact.content.location.kind !== "payload") throw new Error("fixture output is missing");
  writeFileSync(join(payloadRoot, artifact.content.location.path), bytes);
  artifact.content.sha256 = sha256(bytes);
  artifact.content.sizeBytes = bytes.length;
  const manifestBytes = `${JSON.stringify(manifest)}\n`;
  writeFileSync(manifestPath, manifestBytes);
  const request = fixtureRequest(inplace, "head", join(dir, "admission"));
  return { ...request, pin: { ...request.pin!, manifestPath, payloadRoot, manifestSha256: sha256(manifestBytes) } };
}

describe("readBuildArtifact", () => {
  it("reads immutable original and generated bytes separately after an in-place transform", async () => {
    const secretPolicy = policy();
    const admission = await admitted(fixtureRequest(inplace, "head", join(home, `admission-${++serial}`)), secretPolicy);
    try {
      const original = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-original", range: null, byteBudget: 65_536,
      }, secretPolicy);
      const generated = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-output", range: null, byteBudget: 65_536,
      }, secretPolicy);
      expect(original).toMatchObject({ ok: true, result: {
        citation: { manifestSha256: admission.manifestSha256, artifactId: "pricing-original" }, origin: "authored",
        text: expect.stringContaining("@FACTOR@"), delivery: { complete: true, truncated: false, nextCursor: null },
      } });
      expect(generated).toMatchObject({ ok: true, result: {
        citation: { manifestSha256: admission.manifestSha256, artifactId: "pricing-output" }, origin: "materialized",
        text: expect.stringContaining("quantity * 12"), delivery: { complete: true, truncated: false, nextCursor: null },
      } });
      expect(original.ok && original.result.text).not.toBe(generated.ok && generated.result.text);
      if (!generated.ok) throw new Error(generated.error.message);
      expect(generated.result.lineage).toEqual(expect.arrayContaining([
        expect.objectContaining({ transformationId: "pricing-inplace", basis: "exporter-recorded", direction: "output" }),
      ]));
    } finally {
      rmSync(admission.frozen.scratch, { recursive: true, force: true });
    }
  });

  it("binds reads to the admitted manifest and reports a too-small budget as an error, never empty success", async () => {
    const secretPolicy = policy();
    const admission = await admitted(fixtureRequest(inplace, "head", join(home, `identity-${++serial}`)), secretPolicy);
    try {
      await expect(readBuildArtifact(admission, {
        manifestSha256: "f".repeat(64), artifactId: "pricing-output", range: null, byteBudget: 65_536,
      }, secretPolicy)).resolves.toMatchObject({ ok: false, error: { code: "snapshot-mismatch" } });
      const small = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-output", range: null, byteBudget: 1,
      }, secretPolicy);
      expect(small).toMatchObject({ ok: false, error: { code: "budget-too-small", requiredBytes: expect.any(Number) } });
    } finally {
      rmSync(admission.frozen.scratch, { recursive: true, force: true });
    }
  });

  it("refreshes secret screening before every exposure", async () => {
    let values: readonly string[] = [];
    let refreshes = 0;
    const secretPolicy = policy(async () => { refreshes++; return values; });
    const admission = await admitted(fixtureRequest(inplace, "head", join(home, `refresh-${++serial}`)), secretPolicy);
    try {
      const clean = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-output", range: null, byteBudget: 65_536,
      }, secretPolicy);
      expect(clean).toMatchObject({ ok: true });
      values = ["public final class Pricing"];
      const held = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-output", range: null, byteBudget: 65_536,
      }, secretPolicy);
      expect(held).toMatchObject({ ok: false, error: { code: "secret-detected" } });
      expect(JSON.stringify(held)).not.toContain("public final class Pricing");
      expect(refreshes).toBe(3); // admission plus both reads
    } finally {
      rmSync(admission.frozen.scratch, { recursive: true, force: true });
    }
  });

  it("withholds refreshed citation and lineage metadata without rewriting identities", async () => {
    let values: readonly string[] = [];
    const secretPolicy = policy(async () => values);
    const admission = await admitted(fixtureRequest(inplace, "head", join(home, `metadata-${++serial}`)), secretPolicy);
    try {
      values = ["pricing-inplace"];
      const reply = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-output", range: null, byteBudget: 65_536,
      }, secretPolicy);
      expect(reply).toMatchObject({ ok: false, error: { code: "secret-detected" } });
      expect(JSON.stringify(reply)).not.toContain("pricing-inplace");
    } finally {
      rmSync(admission.frozen.scratch, { recursive: true, force: true });
    }
  });

  it("preserves an admitted UTF-8 BOM byte-for-byte", async () => {
    const original = inplace.outputBytes.get("pricing-output");
    if (!original) throw new Error("fixture output bytes are missing");
    const bytes = Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(original)]);
    const secretPolicy = policy();
    const admission = await admitted(republishedOutput(bytes), secretPolicy);
    try {
      const reply = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-output", range: null, byteBudget: 65_536,
      }, secretPolicy);
      if (!reply.ok) throw new Error(reply.error.message);
      expect(Buffer.from(reply.result.text, "utf8")).toEqual(bytes);
    } finally {
      rmSync(admission.frozen.scratch, { recursive: true, force: true });
    }
  });

  it("returns unsupported encoding as typed unavailability instead of transcoding", async () => {
    const secretPolicy = policy();
    const admission = await admitted(republishedEncoding("ISO-8859-1"), secretPolicy);
    try {
      const reply = await readBuildArtifact(admission, {
        manifestSha256: admission.manifestSha256, artifactId: "pricing-output", range: null, byteBudget: 65_536,
      }, secretPolicy);
      expect(reply).toMatchObject({ ok: false, error: { code: "unsupported-encoding" } });
      expect(JSON.stringify(reply)).not.toContain(readFileSync(admission.frozen.available.get("pricing-output")!.path, "utf8"));
    } finally {
      rmSync(admission.frozen.scratch, { recursive: true, force: true });
    }
  });
});
