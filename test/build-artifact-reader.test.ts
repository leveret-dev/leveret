function policy(refresh: () => Promise<readonly string[]> = async () => []): SecretPolicy {
  return {
    id: "artifact-reader-test", available: false, knownValues: new Set(), refreshKnownValues: refresh,
    additionalRules: [], nonSecretValues: new Set(),
  };
}

async function admitted(request: BuildEvidenceRequest, secretPolicy: SecretPolicy): Promise<AdmittedBuildEvidence> {
  const result = await admitBuildEvidence(request, secretPolicy);
  if (result.outcome !== "admitted") throw new Error(`expected admitted export, got ${result.outcome}`);
  return result;
}

function republishedEncoding(encoding: string): BuildEvidenceRequest {
  const dir = join(home, `encoding-${++serial}`);
  const payloadRoot = join(dir, "payload");
  const manifestPath = join(dir, "manifest.json");
  mkdirSync(dir, { recursive: true });
  cpSync(inplace.pins.head.payloadRoot, payloadRoot, { recursive: true });
  const manifest = structuredClone(inplace.manifests.head) as BuildEvidenceManifest;
  const artifact = manifest.artifacts.find((item) => item.id === "pricing-output");
  if (!artifact || artifact.availability !== "available" || artifact.kind !== "file") throw new Error("fixture output is missing");
  artifact.encoding = encoding;
  const bytes = `${JSON.stringify(manifest)}\n`;
  writeFileSync(manifestPath, bytes);
  const request = fixtureRequest(inplace, "head", join(dir, "admission"));
  return { ...request, pin: { ...request.pin!, manifestPath, payloadRoot, manifestSha256: sha256(bytes) } };
}

function republishedOutput(bytes: Buffer): BuildEvidenceRequest {
  const dir = join(home, `bytes-${++serial}`);
  const payloadRoot = join(dir, "payload");
  const manifestPath = join(dir, "manifest.json");
  mkdirSync(dir, { recursive: true });
  cpSync(inplace.pins.head.payloadRoot, payloadRoot, { recursive: true });
  const manifest = structuredClone(inplace.manifests.head) as BuildEvidenceManifest;
  const artifact = manifest.artifacts.find((item) => item.id === "pricing-output");
  if (!artifact || artifact.availability !== "available" || artifact.kind !== "file" ||
    artifact.content.location.kind !== "payload") throw new Error("fixture output is missing");
  writeFileSync(join(payloadRoot, artifact.content.location.path), bytes);
  artifact.content.sha256 = sha256(bytes);
  artifact.content.sizeBytes = bytes.length;
  const manifestBytes = `${JSON.stringify(manifest)}\n`;
  writeFileSync(manifestPath, manifestBytes);
  const request = fixtureRequest(inplace, "head", join(dir, "admission"));
  return { ...request, pin: { ...request.pin!, manifestPath, payloadRoot, manifestSha256: sha256(manifestBytes) } };
}

